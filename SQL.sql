-- Função para converter HH:MM:SS para número
CREATE OR REPLACE FUNCTION ConvertToRanking(pontuacao VARCHAR2) RETURN NUMBER IS
  hours NUMBER;
  minutes NUMBER;
  seconds NUMBER;
  ranking NUMBER;
BEGIN
  -- Extrair horas, minutos e segundos
  hours := TO_NUMBER(SUBSTR(pontuacao, 1, 2));
  minutes := TO_NUMBER(SUBSTR(pontuacao, 4, 2));
  seconds := TO_NUMBER(SUBSTR(pontuacao, 7, 2));

  -- Calcular o ranking
  ranking := (hours * 3600 + minutes * 60 + seconds);

  RETURN ranking;
END;
/

-- Atualiza a coluna Pontuacao_Ranking com base na função ConvertToRanking
UPDATE USER_DATA
SET Pontuacao_Ranking = ConvertToRanking(PONTUACAO);

