-- Cria um gatilho para calcular Pontuacao_Ranking antes de inserir um novo registro na tabela USER_DATA
CREATE OR REPLACE TRIGGER trg_calculate_ranking
BEFORE INSERT ON USER_DATA
FOR EACH ROW
BEGIN
  :NEW.Pontuacao_Ranking := ConvertToRanking(:NEW.PONTUACAO);
END;
